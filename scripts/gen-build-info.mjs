/**
 * Generates src/build-info.ts with the app version (from package.json) and the
 * current build timestamp, so the Settings screen can display them for support
 * and debugging. Run automatically before every build (see package.json).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const buildDate = new Date().toISOString();

// Keep the Android native versionName in sync with package.json. This is
// CRITICAL for the OTA updater: Capgo resets any stored OTA bundle back to the
// APK's builtin bundle when the native version CHANGES (resetWhenUpdate). If
// versionName stays constant across builds, the plugin never resets and can
// keep serving a STALE downloaded bundle even after a clean reinstall (which
// previously showed the wrong version and caused blank screens). versionCode is
// bumped to a stable integer derived from the semver so each release differs.
try {
  const gradlePath = join(root, 'android', 'app', 'build.gradle');
  let gradle = readFileSync(gradlePath, 'utf8');
  const m = /(\d+)\.(\d+)\.(\d+)/.exec(pkg.version);
  if (m) {
    const [, maj, min, pat] = m.map(Number);
    const code = maj * 10000 + min * 100 + pat; // 1.3.9 -> 10309
    const before = gradle;
    gradle = gradle
      .replace(/versionName\s+"[^"]*"/, `versionName "${pkg.version}"`)
      .replace(/versionCode\s+\d+/, `versionCode ${code}`);
    if (gradle !== before) {
      writeFileSync(gradlePath, gradle, 'utf8');
      console.log(`android build.gradle synced: versionName ${pkg.version}, versionCode ${code}`);
    }
  }
} catch (e) {
  console.warn('could not sync android versionName (ok on web-only builds):', e.message);
}

const contents = `// AUTO-GENERATED by scripts/gen-build-info.mjs - do not edit by hand.
// Regenerated on every build (prebuild/prestart hooks in package.json).
export const BUILD_INFO = {
  version: '${pkg.version}',
  buildDate: '${buildDate}',
} as const;
`;

writeFileSync(join(root, 'src', 'build-info.ts'), contents, 'utf8');
console.log(`build-info.ts written: v${pkg.version} @ ${buildDate}`);
