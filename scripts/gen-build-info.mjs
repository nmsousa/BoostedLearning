/**
 * Generates src/build-info.ts with the app version (from package.json) and the
 * current build timestamp, so the Settings screen can display them for support
 * and debugging. Run automatically before every build (see package.json).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const buildDate = new Date().toISOString();

const contents = `// AUTO-GENERATED by scripts/gen-build-info.mjs - do not edit by hand.
// Regenerated on every build (prebuild/prestart hooks in package.json).
export const BUILD_INFO = {
  version: '${pkg.version}',
  buildDate: '${buildDate}',
} as const;
`;

writeFileSync(join(root, 'src', 'build-info.ts'), contents, 'utf8');
console.log(`build-info.ts written: v${pkg.version} @ ${buildDate}`);
