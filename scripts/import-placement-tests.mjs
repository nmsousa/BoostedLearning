/**
 * Import the CEFR placement tests (JSON from "CEFR - Test") into the app:
 * writes src/app/maps/explore-plus/lessons/placement-bank.ts.
 *
 *   node scripts/import-placement-tests.mjs                 # Long version (default)
 *   node scripts/import-placement-tests.mjs "<path>.json"   # any other version (e.g. Short)
 *
 * Every item keeps its id, CEFR band, skill, prompt, options, answer,
 * explanation and (listening) audio transcript. The transcript is never shown
 * in the app; it is read aloud.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2]
  ?? join(root, '..', 'CEFR - Test', 'Long version', 'boostionary-french-placement-tests-v1.json');
const data = JSON.parse(readFileSync(src, 'utf8'));

const BAND = { 'Pre-A1': 'pre-a1', A1: 'a1', A2: 'a2', B1: 'b1', B2: 'b2', C1: 'c1', C2: 'c2' };
const errors = [];
const toItem = (it) => {
  const band = BAND[it.cefr];
  const answer = it.options.findIndex(o => o.id === it.correctOption);
  if (!band) errors.push(`${it.id}: unknown CEFR ${it.cefr}`);
  if (answer < 0) errors.push(`${it.id}: answer ${it.correctOption} not in options`);
  const item = {
    id: it.id, band, skill: it.skill, prompt: it.prompt,
    options: it.options.map(o => o.text), answer, explanation: it.explanation ?? '',
  };
  if (it.audio?.transcript) item.audio = it.audio.transcript;
  return item;
};

const globalItems = data.globalTest.items.map(toItem);
const levelItems = {};
for (const t of data.levelTests) {
  const items = t.items.map(toItem);
  const band = items[0]?.band ?? BAND[t.level];
  levelItems[band] = items;
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const out = `/**
 * GENERATED by scripts/import-placement-tests.mjs from
 * "${src.split(/[\\/]/).slice(-2).join('/')}" (${data.schemaVersion}). Do not edit by hand:
 * edit the JSON and re-run the script.
 *
 * Original Boostionary-authored items; an unofficial, low-stakes placement
 * check (not a DELF/DALF/TCF certificate). Answer keys ship with the app.
 */
import type { PlacementItem, PlacementBand } from './placement-types';

export const GLOBAL_ITEMS: PlacementItem[] = ${JSON.stringify(globalItems, null, 2)};

export const LEVEL_ITEMS: Partial<Record<PlacementBand, PlacementItem[]>> = ${JSON.stringify(levelItems, null, 2)};
`;
writeFileSync(join(root, 'src/app/maps/explore-plus/lessons/placement-bank.ts'), out);
console.log(`placement-bank.ts written: ${globalItems.length} global items, ${Object.values(levelItems).flat().length} level-test items (${Object.keys(levelItems).join(', ')}).`);
