/**
 * Audio Service
 *
 * Plays word audio two ways so they can be compared:
 *  - `playRecorded(url)`: the pre-recorded clip from the deck's audioUrl.
 *  - `playTts(text, langCode)`: device text-to-speech via the TTS service.
 *
 * (Temporary: both are exposed side-by-side for A/B comparison. The intended
 * end state is a single hybrid — recorded when available, TTS fallback.)
 *
 * Respects the Settings audio-speed preference. Web/no-audio environments
 * degrade to no-ops.
 *
 * @module app/services
 */

import { Injectable, inject } from '@angular/core';
import { HttpClient } from '@angular/common/http';
import { firstValueFrom } from 'rxjs';
import { SettingsService } from './settings.service';
import { createTTSService, TTSService } from '../../services/tts';

/** Map an app language code to a BCP 47 tag for TTS voice selection. */
const LANG_TO_BCP47: Record<string, string> = {
  nl: 'nl-NL',
  fr: 'fr-FR',
  es: 'es-ES',
  en: 'en-US',
  de: 'de-DE',
};

/** Languages that ship a bundled offline-audio manifest (assets/audio/<lang>). */
const LOCAL_AUDIO_LANGS = ['fr'];

/** One entry in a generated audio manifest.json (scripts/gen-audio.mjs). */
interface ManifestEntry {
  /** MP3 filename within the language folder. */
  file: string;
  /** Where the clip came from: a borrowed Duolingo recording or our TTS. */
  source: 'duolingo' | 'tts' | 'unknown';
  /** TTS voice name, when source === 'tts'. */
  voice?: string;
}

@Injectable({
  providedIn: 'root',
})
export class AudioService {
  private settings = inject(SettingsService);
  private http = inject(HttpClient);
  private tts: TTSService = createTTSService();
  private audioEl: HTMLAudioElement | null = null;

  /** A deliberately slow rate for the "turtle" (repeat slower) button. */
  private readonly SLOW_RATE = 0.6;

  /**
   * Bundled offline pronunciation audio: langCode → (normalized text →
   * { path, source }). Pre-generated by scripts/gen-audio.mjs and shipped in
   * assets, so a word or sentence plays a LOCAL file with no internet and no
   * device voice. Loaded lazily and cached (including a cached "miss" so we
   * don't refetch). `source` tells where the clip came from (admin-only UI).
   */
  private localAudio = new Map<string, Map<string, { path: string; source: ManifestEntry['source'] }>>();
  private localAudioLoads = new Map<string, Promise<void>>();

  /** Play a pre-recorded clip from a URL. Returns true if playback started. */
  async playRecorded(url: string | undefined | null, rate?: number): Promise<boolean> {
    if (!url) return false;
    try {
      // Reuse a single element so a new play cancels the previous.
      if (!this.audioEl) {
        this.audioEl = typeof Audio !== 'undefined' ? new Audio() : null;
      }
      if (!this.audioEl) return false;

      this.tts.stop(); // don't overlap with TTS
      this.audioEl.pause();
      this.audioEl.src = url;
      this.audioEl.playbackRate = rate ?? this.settings.audioSpeed();
      await this.audioEl.play();
      return true;
    } catch (err) {
      console.warn('AudioService: recorded playback failed', err);
      return false;
    }
  }

  /**
   * Speak text with device TTS in the given app language.
   * Returns `{ ok, reason? }` so the UI can explain a failure (e.g. no voice).
   */
  async playTts(text: string, langCode: string, rate?: number): Promise<{ ok: boolean; reason?: string }> {
    if (!text) return { ok: false, reason: 'No text' };
    const lang = LANG_TO_BCP47[langCode] ?? langCode;

    if (!this.tts.isSupported()) {
      return { ok: false, reason: 'Speech is not supported on this device.' };
    }
    if (!this.tts.hasVoiceFor(lang)) {
      return { ok: false, reason: `No voice installed for ${lang} on this device.` };
    }

    if (this.audioEl) this.audioEl.pause(); // don't overlap with recorded
    const result = await this.tts.speak(text, {
      lang,
      rate: rate ?? this.settings.audioSpeed(),
    });
    if (!result.success) {
      console.warn('AudioService: TTS failed', result.error);
      return { ok: false, reason: result.error };
    }
    return { ok: true };
  }

  /** Normalize text to match the generated manifest keys (NFC, straight
   *  apostrophe, lower-case, single spaces). Mirrors gen-audio.mjs. */
  private audioKey(s: string): string {
    return s.normalize('NFC').replace(/[’‘]/g, "'").toLowerCase().replace(/\s+/g, ' ').trim();
  }

  /** Load & cache the offline-audio manifest for a language (once). A missing
   *  manifest is fine — we cache an empty map so we don't refetch. */
  private async ensureLocalAudio(langCode: string): Promise<void> {
    if (!LOCAL_AUDIO_LANGS.includes(langCode)) return;
    if (this.localAudio.has(langCode)) return;
    let load = this.localAudioLoads.get(langCode);
    if (!load) {
      load = (async () => {
        const map = new Map<string, { path: string; source: ManifestEntry['source'] }>();
        try {
          const json = await firstValueFrom(
            this.http.get<Record<string, ManifestEntry | string>>(
              `assets/audio/${langCode}/manifest.json`,
            ),
          );
          if (json) {
            for (const [text, entry] of Object.entries(json)) {
              // Entry is { file, source, voice? }; tolerate the old plain-string form.
              const file = typeof entry === 'string' ? entry : entry?.file;
              const source = typeof entry === 'string' ? 'unknown' : (entry?.source ?? 'unknown');
              if (file) {
                map.set(this.audioKey(text), { path: `assets/audio/${langCode}/${file}`, source });
              }
            }
          }
        } catch {
          // No manifest bundled — fall back to streamed/TTS.
        }
        this.localAudio.set(langCode, map);
      })();
      this.localAudioLoads.set(langCode, load);
    }
    await load;
  }

  /** The bundled local asset path for a piece of text, if one exists. */
  private localAudioFor(langCode: string, text: string): string | undefined {
    return this.localAudio.get(langCode)?.get(this.audioKey(text))?.path;
  }

  /**
   * Where a word's bundled local clip came from — 'duolingo' (borrowed course
   * recording), 'tts' (our generated voice), or undefined if there's no local
   * clip for it. Used by admin-only UI to flag which words still use the
   * Duolingo voice. Call `ensureLocalAudio(langCode)` first (e.g. the manifest
   * is already loaded once any audio has played).
   */
  localAudioSource(langCode: string, text: string): ManifestEntry['source'] | undefined {
    return this.localAudio.get(langCode)?.get(this.audioKey(text))?.source;
  }

  /** Preload the offline-audio manifest for a language (safe to await). Lets a
   *  page that shows source badges ensure the data is ready before rendering. */
  async preloadLocalAudio(langCode: string): Promise<void> {
    await this.ensureLocalAudio(langCode);
  }

  /** Whether device TTS has a voice for the given app language. */
  hasTtsVoice(langCode: string): boolean {
    const lang = LANG_TO_BCP47[langCode] ?? langCode;
    return this.tts.hasVoiceFor(lang);
  }

  /**
   * Play a word's audio with the preferred source: the recorded clip when
   * available, falling back to device TTS when there's no recording or the
   * recording fails to play. Returns `{ ok, reason? }` so the UI can report a
   * genuine failure (e.g. no recording AND no voice).
   */
  async playWord(
    text: string,
    audioUrl: string | undefined | null,
    langCode: string,
    slow = false
  ): Promise<{ ok: boolean; reason?: string }> {
    const rate = slow ? this.SLOW_RATE : undefined;

    // 1. Bundled LOCAL file first — works offline, no device voice needed.
    //    Covers Tree words AND example sentences, without each caller having to
    //    pass a URL. If the passed audioUrl already points at a local asset
    //    (Tree cards do), this is a cheap no-op lookup that finds the same file.
    await this.ensureLocalAudio(langCode);
    const local = this.localAudioFor(langCode, text);
    if (local) {
      const played = await this.playRecorded(local, rate);
      if (played) return { ok: true };
    }

    // 2. The passed-in clip (e.g. the streamed course recording).
    if (audioUrl) {
      const played = await this.playRecorded(audioUrl, rate);
      if (played) return { ok: true };
      // Recorded failed (network/expired URL) — fall through to TTS.
    }

    // 3. Device TTS as a last resort.
    return this.playTts(text, langCode, rate);
  }
}
